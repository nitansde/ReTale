const dictionaries: Record<Locale, MessageDictionary> = {
  zh: zhMessages,
  en: enMessages,
}

export function isLocale(value: string): value is Locale {
  return SUPPORTED_LOCALES.includes(value as Locale)
}

export function getClientLocale(): Locale {
  if (typeof document !== 'undefined') {
    const documentLocale = document.documentElement.dataset.locale
    if (documentLocale && isLocale(documentLocale)) {
      return documentLocale
    }
  }

  if (typeof window !== 'undefined') {
    try {
      const stored = window.localStorage.getItem(LOCALE_STORAGE_KEY)
      if (stored && isLocale(stored)) {
        return stored
      }
    } catch {
      // Ignore storage access failures in restricted or test environments.
    }
  }

  return 'zh'
}

export function getMessage(locale: Locale, key: TranslationKey, values?: TranslationValues) {
  const template = dictionaries[locale][key] ?? dictionaries.zh[key] ?? String(key)

  if (!values) {
    return template
  }

  return template.replace(/\{\{(.*?)\}\}/g, (_, rawKey: string) => {
    const value = values[rawKey.trim()]
    return value === undefined ? '' : String(value)
  })
}
